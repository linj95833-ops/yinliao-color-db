const {chromium}=require('playwright');
const fs=require('fs');
const path=require('path');
(async()=>{
 const browser=await chromium.launch({channel:'chrome',headless:true});
 const page=await browser.newPage({viewport:{width:1500,height:1100},deviceScaleFactor:1});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(process.env.STUDIO_URL||'http://127.0.0.1:8877');
 await page.waitForFunction(()=>document.querySelectorAll('.item').length===36);
 await page.screenshot({path:'report/v2/ui-empty.png',fullPage:true});
 await page.locator('#upload').setInputFiles(process.env.STUDIO_TEST_IMAGE||'examples/portrait_sample.png');
 await page.waitForFunction(()=>session&&!busy,{timeout:60000});
 await page.locator('#search').fill('康师傅冰红茶');
 await page.getByRole('button',{name:'康师傅冰红茶',exact:true}).click();
 const maskBefore=await page.evaluate(()=>exportMask());
 await page.locator('#editDetails summary').click();
 const r=await page.locator('#editCanvas').boundingBox();
 await page.mouse.move(r.x+r.width*.5,r.y+r.height*.7);await page.mouse.down();await page.mouse.move(r.x+r.width*.6,r.y+r.height*.7,{steps:8});await page.mouse.up();
 const maskAfter=await page.evaluate(()=>exportMask());
 if(maskBefore===maskAfter)throw Error('Brush did not change mask');
 await page.locator('#undo').click();
 if(await page.evaluate(()=>exportMask())!==maskBefore)throw Error('Undo did not restore mask');
 await page.locator('#generate').click();
 await page.waitForFunction(()=>!busy&&view==='result',{timeout:60000});
 const download=await page.locator('#download').getAttribute('href');
 const response=await page.request.get(new URL(download,page.url()).href);
 if(!response.ok()||!response.headers()['content-type'].startsWith('image/png'))throw Error('PNG download failed');
 await page.screenshot({path:'report/v2/ui-result.png',fullPage:true});
 await page.locator('#originalTab').click();
 await page.locator('#maskTab').click();
 if(await page.locator('#editCanvas').evaluate(e=>getComputedStyle(e).pointerEvents)!=='auto')throw Error('Mask editor inactive');
 await page.locator('#search').fill('');
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'report/v2/ui-mobile.png',fullPage:true});
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Mobile horizontal overflow');
 await page.locator('#upload').setInputFiles('examples/portrait_sample.png');
 await page.waitForFunction(()=>!busy&&document.querySelector('#photoInfo').textContent.includes('portrait_sample'),{timeout:60000});
 if(!await page.locator('#resultTab').isDisabled())throw Error('New upload retained stale result');
 if(errors.length)throw Error(errors.join('\n'));
 fs.writeFileSync('report/v2/ui-test.json',JSON.stringify({passed:true,library:36,brush:true,undo:true,download:true,mobile:true,newUpload:true,consoleErrors:errors},null,2));
 console.log('UI PASS: 36 assets, upload, select, brush, undo, render, PNG, mobile, new upload');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
